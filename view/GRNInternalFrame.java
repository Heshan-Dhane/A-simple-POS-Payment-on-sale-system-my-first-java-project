    private void btnAddStockActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnAddStockActionPerformed
        try {
            String itemCode = txtItemCode.getText().trim();
            String qtyStr = txtQty.getText().trim();
            String priceStr = txtPrice.getText().trim();

            if (itemCode.isEmpty() || qtyStr.isEmpty() || priceStr.isEmpty()) {
                javax.swing.JOptionPane.showMessageDialog(this, "Please fill in Item Code, Quantity, and Price!", "Validation Error", javax.swing.JOptionPane.WARNING_MESSAGE);
                return;
            }

            int qtyReceived = Integer.parseInt(qtyStr);
            double buyingPrice = Double.parseDouble(priceStr);

            // Check if item exists in the database 
            try (java.sql.Connection conn = java.sql.DriverManager.getConnection("jdbc:mysql://localhost:3306/brightmart_db", "root", "Primeheshanheidisql123$$"); java.sql.PreparedStatement pst = conn.prepareStatement("SELECT description FROM products WHERE item_code = ?")) {

                pst.setString(1, itemCode);
                java.sql.ResultSet rs = pst.executeQuery();

                if (rs.next()) {
                    String description = rs.getString("description");

                    // Add to table locally 
                    javax.swing.table.DefaultTableModel model = (javax.swing.table.DefaultTableModel) jTableGRN.getModel();
                    model.addRow(new Object[]{itemCode, description, qtyReceived, buyingPrice});

                    // Update running total
                    calculateBatchTotal();

                    // Clear input fields for next item
                    txtItemCode.setText("");
                    txtQty.setText("");
                    txtPrice.setText("");
                } else {
                    javax.swing.JOptionPane.showMessageDialog(this, "Error: Item Code does not exist in the products table!", "Database Error", javax.swing.JOptionPane.ERROR_MESSAGE);
                }
            }

        } catch (NumberFormatException e) {
            javax.swing.JOptionPane.showMessageDialog(this, "Quantity and Price must be valid numbers.", "Format Error", javax.swing.JOptionPane.WARNING_MESSAGE);
        } catch (Exception e) {
            javax.swing.JOptionPane.showMessageDialog(this, "Database Connection Failed: " + e.getMessage(), "Connection Error", javax.swing.JOptionPane.ERROR_MESSAGE);
        }
    }//GEN-LAST:event_btnAddStockActionPerformed

    private void btnProcessPaymentActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnProcessPaymentActionPerformed
        String supplierCode = txtSupplier.getText().trim();
        javax.swing.table.DefaultTableModel model = (javax.swing.table.DefaultTableModel) jTableGRN.getModel();

        if (supplierCode.isEmpty()) {
            javax.swing.JOptionPane.showMessageDialog(this, "Please enter the Supplier ID!", "Validation Error", javax.swing.JOptionPane.WARNING_MESSAGE);
            return;
        }

        if (model.getRowCount() == 0) {
            javax.swing.JOptionPane.showMessageDialog(this, "The delivery batch is empty! Add items first.", "Validation Error", javax.swing.JOptionPane.WARNING_MESSAGE);
            return;
        }

        try (java.sql.Connection conn = java.sql.DriverManager.getConnection("jdbc:mysql://localhost:3306/brightmart_db", "root", "Primeheshanheidisql123$$")) {
            conn.setAutoCommit(false); // Start transaction

            double totalAmount = 0.0;
            for (int i = 0; i < model.getRowCount(); i++) {
                int qty = Integer.parseInt(model.getValueAt(i, 2).toString());
                double price = Double.parseDouble(model.getValueAt(i, 3).toString());
                totalAmount += (qty * price);
            }

            // Insert into GRN master table
            String insertGrn = "INSERT INTO grn (sup_code, received_date, total_amount) VALUES (?, NOW(), ?)";
            java.sql.PreparedStatement pstGrn = conn.prepareStatement(insertGrn, java.sql.Statement.RETURN_GENERATED_KEYS);
            pstGrn.setString(1, supplierCode);
            pstGrn.setDouble(2, totalAmount);
            pstGrn.executeUpdate();

            java.sql.ResultSet rsKey = pstGrn.getGeneratedKeys();
            int grnId = 0;
            if (rsKey.next()) {
                grnId = rsKey.getInt(1);
            }

            // Insert into grn_items and update products stock
            String insertGrnItems = "INSERT INTO grn_items (grn_id, item_code, qty_received) VALUES (?, ?, ?)";
            String updateStock = "UPDATE products SET current_stock = current_stock + ? WHERE item_code = ?";

            java.sql.PreparedStatement pstGrnItems = conn.prepareStatement(insertGrnItems);
            java.sql.PreparedStatement pstStock = conn.prepareStatement(updateStock);

            for (int i = 0; i < model.getRowCount(); i++) {
                String itemCode = model.getValueAt(i, 0).toString();
                int qty = Integer.parseInt(model.getValueAt(i, 2).toString());

                pstGrnItems.setInt(1, grnId);
                pstGrnItems.setString(2, itemCode);
                pstGrnItems.setInt(3, qty);
                pstGrnItems.addBatch();

                pstStock.setInt(1, qty);
                pstStock.setString(2, itemCode);
                pstStock.addBatch();
            }

            pstGrnItems.executeBatch();
            pstStock.executeBatch();
            conn.commit();

            javax.swing.JOptionPane.showMessageDialog(this, "Payment processed successfully! Stock updated.", "Success", javax.swing.JOptionPane.INFORMATION_MESSAGE);
            model.setRowCount(0);
            txtSupplier.setText("");
            BatchTotal.setText("Rs. 0.00");

        } catch (Exception e) {
            javax.swing.JOptionPane.showMessageDialog(this, "Transaction Failed: " + e.getMessage(), "Database Error", javax.swing.JOptionPane.ERROR_MESSAGE);
        }
    }//GEN-LAST:event_btnProcessPaymentActionPerformed

