    private void initClock() {
        javax.swing.JPanel bottomPanel = new javax.swing.JPanel(new java.awt.BorderLayout());

        //clock
        javax.swing.JLabel clockLabel = new javax.swing.JLabel();
        clockLabel.setFont(new java.awt.Font("Poppins", java.awt.Font.BOLD, 12));
        clockLabel.setBorder(javax.swing.BorderFactory.createEmptyBorder(4, 5, 4, 10)); // padding

        javax.swing.JPanel rightAlignPanel = new javax.swing.JPanel(new java.awt.FlowLayout(java.awt.FlowLayout.RIGHT));
        rightAlignPanel.add(clockLabel);
        bottomPanel.add(rightAlignPanel, java.awt.BorderLayout.EAST);

        getContentPane().add(bottomPanel, java.awt.BorderLayout.SOUTH);

        javax.swing.Timer timer = new javax.swing.Timer(1000, (java.awt.event.ActionEvent e) -> {
            java.text.SimpleDateFormat sdf = new java.text.SimpleDateFormat("yyyy-MM-dd  |  hh:mm:ss a");
            clockLabel.setText(sdf.format(new java.util.Date()));
        });
        timer.start();
    }

