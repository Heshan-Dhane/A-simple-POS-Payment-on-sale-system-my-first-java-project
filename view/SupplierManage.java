    private void loadTableData() {
        try {
            Connection conn = DBConnection.getConnection();
            String sql = "SELECT * FROM suppliers";
            PreparedStatement pstmt = conn.prepareStatement(sql);
            ResultSet rs = pstmt.executeQuery();

            DefaultTableModel model = (DefaultTableModel) supplierTbl.getModel();
            model.setRowCount(0);

            while (rs.next()) {
                Object[] row = new Object[4];
                row[0] = rs.getString("sup_code");
                row[1] = rs.getString("name");
                row[2] = rs.getString("address");
                row[3] = rs.getString("contact_details");
                model.addRow(row);
            }
            rs.close();
            pstmt.close();
        } catch (Exception e) {
            JOptionPane.showMessageDialog(this, "Error loading table data: " + e.getMessage(), "System Error", JOptionPane.ERROR_MESSAGE);
        }

    }

