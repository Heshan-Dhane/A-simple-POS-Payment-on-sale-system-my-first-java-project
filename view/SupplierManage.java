    private void addBtnActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_addBtnActionPerformed
        // TODO add your handling code here:
        if (txtSupplierId.getText().isEmpty() || txtSupplierName.getText().isEmpty()
                || txtContact.getText().isEmpty() || txtAddress.getText().isEmpty()) {
            JOptionPane.showMessageDialog(this, "Please fill in all fields.", "Validation Error", JOptionPane.WARNING_MESSAGE);
            return;
        }

        try {
            Connection conn = DBConnection.getConnection();
            String sql = "INSERT INTO suppliers (sup_code, name, address, contact_details) VALUES (?, ?, ?, ?)";
            PreparedStatement pstmt = conn.prepareStatement(sql);
            pstmt.setString(1, txtSupplierId.getText());
            pstmt.setString(2, txtSupplierName.getText());
            pstmt.setString(3, txtAddress.getText());
            pstmt.setString(4, txtContact.getText());

            if (pstmt.executeUpdate() > 0) {
                JOptionPane.showMessageDialog(this, "Supplier added successfully!");
                loadTableData();
                clearBtnActionPerformed(evt);
            }
            pstmt.close();
        } catch (Exception e) {
            JOptionPane.showMessageDialog(this, "Database error: " + e.getMessage(), "System Error", JOptionPane.ERROR_MESSAGE);
        }
    }//GEN-LAST:event_addBtnActionPerformed

    private void updateBtnActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_updateBtnActionPerformed
        // TODO add your handling code here:
        if (txtSupplierId.getText().isEmpty()) {
            JOptionPane.showMessageDialog(this, "Please select a supplier to update.", "Error", JOptionPane.ERROR_MESSAGE);
            return;
        }

        try {
            Connection conn = DBConnection.getConnection();
            String sql = "UPDATE suppliers SET name=?, contact_details=?, address=? WHERE sup_code=?";
            PreparedStatement pstmt = conn.prepareStatement(sql);
            pstmt.setString(1, txtSupplierName.getText());
            pstmt.setString(2, txtContact.getText());
            pstmt.setString(3, txtAddress.getText());
            pstmt.setString(4, txtSupplierId.getText());

            if (pstmt.executeUpdate() > 0) {
                JOptionPane.showMessageDialog(this, "Supplier updated successfully!");
                loadTableData();
                clearBtnActionPerformed(evt);
            }
            pstmt.close();
        } catch (Exception e) {
            JOptionPane.showMessageDialog(this, "Database error: " + e.getMessage(), "System Error", JOptionPane.ERROR_MESSAGE);
        }
    }//GEN-LAST:event_updateBtnActionPerformed

    private void deleteBtnActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_deleteBtnActionPerformed
        // TODO add your handling code here:
        if (txtSupplierId.getText().isEmpty()) {
            JOptionPane.showMessageDialog(this, "Please select a supplier to delete.", "Error", JOptionPane.ERROR_MESSAGE);
            return;
        }

        if (JOptionPane.showConfirmDialog(this, "Delete this supplier?", "Confirm", JOptionPane.YES_NO_OPTION) == JOptionPane.YES_OPTION) {
            try {
                Connection conn = DBConnection.getConnection();
                String sql = "DELETE FROM suppliers WHERE sup_code=?";
                PreparedStatement pstmt = conn.prepareStatement(sql);
                pstmt.setString(1, txtSupplierId.getText());

                if (pstmt.executeUpdate() > 0) {
                    JOptionPane.showMessageDialog(this, "Supplier deleted successfully!");
                    loadTableData();
                    clearBtnActionPerformed(evt);
                }
                pstmt.close();
            } catch (Exception e) {
                JOptionPane.showMessageDialog(this, "Database error: " + e.getMessage(), "System Error", JOptionPane.ERROR_MESSAGE);
            }
        }
    }//GEN-LAST:event_deleteBtnActionPerformed

