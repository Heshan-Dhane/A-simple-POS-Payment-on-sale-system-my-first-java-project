    private void loginActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_loginActionPerformed
        String staffId = txtStaffId.getText();
        String password = new String(txtPassword.getPassword());

        if (staffId.trim().isEmpty() || password.trim().isEmpty()) {
            JOptionPane.showMessageDialog(this, "Please enter both Staff ID and Password.", "Validation Error", JOptionPane.WARNING_MESSAGE);
            return;
        }

        try { //connecting my db 
            Connection conn = DBConnection.getConnection();

            String sql = "SELECT * FROM users WHERE staff_id = ? AND password = ?";
            PreparedStatement pstmt = conn.prepareStatement(sql);
            pstmt.setString(1, staffId);
            pstmt.setString(2, password);

            ResultSet rs = pstmt.executeQuery();

            if (rs.next()) {
                JOptionPane.showMessageDialog(this, "Login Successful! Welcome " + rs.getString("username"));

                Splash splash = new Splash();
                splash.setVisible(true);
                this.dispose();

            } else {
                JOptionPane.showMessageDialog(this, "Invalid Staff ID or Password", "Access Denied", JOptionPane.ERROR_MESSAGE);
                txtStaffId.setText("");
                txtPassword.setText("");
                txtStaffId.requestFocus();
            }

            rs.close();
            pstmt.close();

        } catch (Exception e) {
            JOptionPane.showMessageDialog(this, "Database error: " + e.getMessage(), "System Error", JOptionPane.ERROR_MESSAGE);
            e.printStackTrace();
        }
    }//GEN-LAST:event_loginActionPerformed

