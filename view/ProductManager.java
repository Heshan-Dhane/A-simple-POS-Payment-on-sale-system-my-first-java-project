    private void addBtnActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_addBtnActionPerformed

        if (txtItemCode.getText().isEmpty() || txtDescription.getText().isEmpty()
                || txtUnitPrice.getText().isEmpty() || txtReorderLevel.getText().isEmpty()
                || cmbCategory.getSelectedIndex() == 0) {
            JOptionPane.showMessageDialog(this, "Please fill in all fields.", "Validation Error", JOptionPane.WARNING_MESSAGE);
            return;
        }

        try {

            Connection conn = DBConnection.getConnection();
            String sql = "INSERT INTO products (item_code, description, category, unit_price, reorder_level, current_stock) VALUES (?, ?, ?, ?, ?, 0)";
            PreparedStatement pstmt = conn.prepareStatement(sql);

            /* this code binds the UI data to the SQL query and adds to the database */
            pstmt.setString(1, txtItemCode.getText());
            pstmt.setString(2, txtDescription.getText());
            pstmt.setString(3, cmbCategory.getSelectedItem().toString());
            pstmt.setDouble(4, Double.parseDouble(txtUnitPrice.getText()));
            pstmt.setInt(5, Integer.parseInt(txtReorderLevel.getText()));

            int rowsInserted = pstmt.executeUpdate();
            if (rowsInserted > 0) {
                JOptionPane.showMessageDialog(this, "Product added successfully!");
                loadTableData();

                // this clears the table
                txtItemCode.setText("");
                txtDescription.setText("");
                cmbCategory.setSelectedIndex(0);
                txtUnitPrice.setText("");
                txtReorderLevel.setText("");
            }

            pstmt.close();

        } catch (NumberFormatException nfe) {
            JOptionPane.showMessageDialog(this, "Price and Reorder Level must be valid numbers.", "Input Error", JOptionPane.ERROR_MESSAGE);
        } catch (Exception e) {
            JOptionPane.showMessageDialog(this, "Database error: " + e.getMessage(), "System Error", JOptionPane.ERROR_MESSAGE);
            e.printStackTrace();
        }
    }

    private void loadTableData() {
        try {
            Connection conn = DBConnection.getConnection();

            String sql = "SELECT * FROM products";
            PreparedStatement pstmt = conn.prepareStatement(sql);
            ResultSet rs = pstmt.executeQuery();

            javax.swing.table.DefaultTableModel model = (javax.swing.table.DefaultTableModel) productTbl.getModel();
            model.setRowCount(0);

            while (rs.next()) {
                Object[] row = new Object[6];
                row[0] = rs.getString("item_code");
                row[1] = rs.getString("description");
                row[2] = rs.getString("category");
                row[3] = rs.getDouble("unit_price");
                row[4] = rs.getInt("reorder_level");
                row[5] = rs.getInt("current_stock");
                model.addRow(row);
            }

            rs.close();
            pstmt.close();

        } catch (Exception e) {
            JOptionPane.showMessageDialog(this, "Error loading table data: " + e.getMessage(), "System Error", JOptionPane.ERROR_MESSAGE);
            e.printStackTrace();
        }

    }//GEN-LAST:event_addBtnActionPerformed

