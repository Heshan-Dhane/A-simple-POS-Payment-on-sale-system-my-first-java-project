    private void productTblMouseClicked(java.awt.event.MouseEvent evt) {//GEN-FIRST:event_productTblMouseClicked

        int selectedRow = productTbl.getSelectedRow();
        javax.swing.table.DefaultTableModel model = (javax.swing.table.DefaultTableModel) productTbl.getModel();

        txtItemCode.setText(model.getValueAt(selectedRow, 0).toString());
        txtDescription.setText(model.getValueAt(selectedRow, 1).toString());
        cmbCategory.setSelectedItem(model.getValueAt(selectedRow, 2).toString());
        txtUnitPrice.setText(model.getValueAt(selectedRow, 3).toString());
        txtReorderLevel.setText(model.getValueAt(selectedRow, 4).toString());

        // Disable the Item Code field so the user cannot change the Primary Key by accident
        txtItemCode.setEditable(false);

    }//GEN-LAST:event_productTblMouseClicked

    private void updateBtnActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_updateBtnActionPerformed
        // TODO add your handling code here:                                        
        if (txtItemCode.getText().isEmpty()) {
            JOptionPane.showMessageDialog(this, "Please select a product from the table to update.", "Error", JOptionPane.ERROR_MESSAGE);
            return;
        }

        try {
            Connection conn = DBConnection.getConnection();
            String sql = "UPDATE products SET description=?, category=?, unit_price=?, reorder_level=? WHERE item_code=?";
            PreparedStatement pstmt = conn.prepareStatement(sql);

            pstmt.setString(1, txtDescription.getText());
            pstmt.setString(2, cmbCategory.getSelectedItem().toString());
            pstmt.setDouble(3, Double.parseDouble(txtUnitPrice.getText()));
            pstmt.setInt(4, Integer.parseInt(txtReorderLevel.getText()));
            pstmt.setString(5, txtItemCode.getText());

            int rowsUpdated = pstmt.executeUpdate();
            if (rowsUpdated > 0) {
                JOptionPane.showMessageDialog(this, "Product updated successfully!");
                loadTableData();

                txtItemCode.setText("");
                txtDescription.setText("");
                cmbCategory.setSelectedIndex(0);
                txtUnitPrice.setText("");
                txtReorderLevel.setText("");
                txtItemCode.setEditable(true);
            }
            pstmt.close();
        } catch (Exception e) {
            JOptionPane.showMessageDialog(this, "Database error: " + e.getMessage(), "System Error", JOptionPane.ERROR_MESSAGE);
        }

    }//GEN-LAST:event_updateBtnActionPerformed

    private void deleteBtnActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_deleteBtnActionPerformed

        if (txtItemCode.getText().isEmpty()) {
            JOptionPane.showMessageDialog(this, "Please select a product from the table to delete.", "Error", JOptionPane.ERROR_MESSAGE);
            return;
        }

        int confirm = JOptionPane.showConfirmDialog(this, "Are you sure you want to delete this product?", "Confirm Delete", JOptionPane.YES_NO_OPTION);

        if (confirm == JOptionPane.YES_OPTION) {
            try {
                Connection conn = DBConnection.getConnection();
                String sql = "DELETE FROM products WHERE item_code=?";
                PreparedStatement pstmt = conn.prepareStatement(sql);
                pstmt.setString(1, txtItemCode.getText());

                int rowsDeleted = pstmt.executeUpdate();
                if (rowsDeleted > 0) {
                    JOptionPane.showMessageDialog(this, "Product deleted successfully!");
                    loadTableData();

                    txtItemCode.setText("");
                    txtDescription.setText("");
                    cmbCategory.setSelectedIndex(0);
                    txtUnitPrice.setText("");
                    txtReorderLevel.setText("");
                    txtItemCode.setEditable(true);
                }
                pstmt.close();
            } catch (Exception e) {
                JOptionPane.showMessageDialog(this, "Database error: " + e.getMessage(), "System Error", JOptionPane.ERROR_MESSAGE);
            }
        }

    }//GEN-LAST:event_deleteBtnActionPerformed

