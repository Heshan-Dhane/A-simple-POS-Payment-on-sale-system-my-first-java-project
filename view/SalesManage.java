    private void txtItemCodeKeyPressed(java.awt.event.KeyEvent evt) {//GEN-FIRST:event_txtItemCodeKeyPressed
        // TODO add your handling code here:
        if (evt.getKeyCode() == java.awt.event.KeyEvent.VK_ENTER) {

            if (txtItemCode.getText().isEmpty()) {
                return;
            }

            try {
                Connection conn = DBConnection.getConnection();
                String sql = "SELECT description, unit_price FROM products WHERE item_code = ?";
                PreparedStatement pstmt = conn.prepareStatement(sql);
                pstmt.setString(1, txtItemCode.getText());

                ResultSet rs = pstmt.executeQuery();

                if (rs.next()) {
                    // when the item is found this Auto fills the locked text fields
                    txtItemName.setText(rs.getString("description"));
                    txtPrice.setText(String.valueOf(rs.getDouble("unit_price")));

                    // Automatically move the typing cursor to the Quantity field to save time
                    txtQty.requestFocus();
                } else {
                    JOptionPane.showMessageDialog(this, "Product not found! Check the Item Code.", "Error", JOptionPane.ERROR_MESSAGE);
                    txtItemName.setText("");
                    txtPrice.setText("");
                }

                rs.close();
                pstmt.close();

            } catch (Exception e) {
                JOptionPane.showMessageDialog(this, "Database error: " + e.getMessage(), "System Error", JOptionPane.ERROR_MESSAGE);
            }
        }
    }//GEN-LAST:event_txtItemCodeKeyPressed

    private void addToCartBtnActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_addToCartBtnActionPerformed

        if (txtItemCode.getText().isEmpty() || txtItemName.getText().isEmpty() || txtQty.getText().isEmpty()) {
            JOptionPane.showMessageDialog(this, "Please select an item and enter a quantity.", "Validation Error", JOptionPane.WARNING_MESSAGE);
            return;
        }

        try {
            double price = Double.parseDouble(txtPrice.getText());
            int qty = Integer.parseInt(txtQty.getText());

            java.sql.Connection conn = DBConnection.getConnection();
            String checkStockSql = "SELECT current_stock FROM products WHERE item_code = ?";
            java.sql.PreparedStatement pstmt = conn.prepareStatement(checkStockSql);
            pstmt.setString(1, txtItemCode.getText());
            java.sql.ResultSet rs = pstmt.executeQuery();

            if (rs.next()) {
                int availableStock = rs.getInt("current_stock");
                if (availableStock < qty) {
                    JOptionPane.showMessageDialog(this,
                            "Insufficient stock! Available stock is only: " + availableStock,
                            "Stock Alert",
                            JOptionPane.WARNING_MESSAGE);
                    rs.close();
                    pstmt.close();
                    return;
                }
            }
            rs.close();
            pstmt.close();

            // Calculate Line Total
            double lineTotal = price * qty;
            DefaultTableModel model = (DefaultTableModel) cartTbl.getModel();
            model.addRow(new Object[]{
                txtItemCode.getText(),
                txtItemName.getText(),
                price,
                qty,
                lineTotal
            });

            // this code updates the Grand Total
            grandTotal += lineTotal;
            lblGrandTotal.setText("Rs. " + String.format("%.2f", grandTotal));

            txtItemCode.setText("");
            txtItemName.setText("");
            txtPrice.setText("");
            txtQty.setText("");
            txtItemCode.requestFocus();

        } catch (NumberFormatException nfe) {
            JOptionPane.showMessageDialog(this, "Quantity must be a valid number.", "Input Error", JOptionPane.ERROR_MESSAGE);
        } catch (Exception e) {
            JOptionPane.showMessageDialog(this, "Database error: " + e.getMessage(), "System Error", JOptionPane.ERROR_MESSAGE);
        }
    }//GEN-LAST:event_addToCartBtnActionPerformed

    private void checkoutBtnActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_checkoutBtnActionPerformed
        DefaultTableModel model = (DefaultTableModel) cartTbl.getModel();

        if (model.getRowCount() == 0) {
            JOptionPane.showMessageDialog(this, "The cart is empty. Add items before checking out.", "Error", JOptionPane.ERROR_MESSAGE);
            return;
        }

        int saleId = 0; // Declare saleId here so the entire method can access it!

        try {
            Connection conn = DBConnection.getConnection();

            // this saves the main sale record 
            String salesSql = "INSERT INTO sales (sale_date, grand_total) VALUES (CURRENT_DATE, ?)";

            PreparedStatement pstmtSales = conn.prepareStatement(salesSql, java.sql.Statement.RETURN_GENERATED_KEYS);
            pstmtSales.setDouble(1, grandTotal);
            pstmtSales.executeUpdate();

            ResultSet rs = pstmtSales.getGeneratedKeys();
            if (rs.next()) {
                saleId = rs.getInt(1);
            }

            String itemsSql = "INSERT INTO sales_items (invoice_id, item_code, qty_sold, line_total) VALUES (?, ?, ?, ?)";
            PreparedStatement pstmtItems = conn.prepareStatement(itemsSql);

            String stockSql = "UPDATE products SET current_stock = current_stock - ? WHERE item_code = ?";
            PreparedStatement pstmtStock = conn.prepareStatement(stockSql);

            for (int i = 0; i < model.getRowCount(); i++) {
                String itemCode = model.getValueAt(i, 0).toString();
                int qtySold = Integer.parseInt(model.getValueAt(i, 3).toString());
                double lineTotal = Double.parseDouble(model.getValueAt(i, 4).toString());

                // this code Saves to sales items
                pstmtItems.setInt(1, saleId);
                pstmtItems.setString(2, itemCode);
                pstmtItems.setInt(3, qtySold);
                pstmtItems.setDouble(4, lineTotal);
                pstmtItems.executeUpdate();

                // this code deduct from current stock in products table
                pstmtStock.setInt(1, qtySold);
                pstmtStock.setString(2, itemCode);
                pstmtStock.executeUpdate();
            }
            pstmtStock.close();
            JOptionPane.showMessageDialog(this, "Payment processed successfully! Sale ID: " + saleId);

            model.setRowCount(0);
            grandTotal = 0.0;
            lblGrandTotal.setText("Rs. 0.00");

            pstmtSales.close();
            pstmtItems.close();

        } catch (Exception e) {
            JOptionPane.showMessageDialog(this, "Database error: " + e.getMessage(), "System Error", JOptionPane.ERROR_MESSAGE);
            return; // Stop execution if database save fails
        }

        // after the payment is sucess this code helps to connect the jaspersoft report
        try {
            java.io.InputStream reportStream = getClass().getResourceAsStream("/reports/BM_Receipt.jasper");

            if (reportStream == null) {
                JOptionPane.showMessageDialog(this, "Receipt template not found in application resources!", "Error", JOptionPane.ERROR_MESSAGE);
                return;
            }

            java.util.HashMap<String, Object> parameters = new java.util.HashMap<>();
            parameters.put("Parameter_SaleID", saleId);

            net.sf.jasperreports.engine.JasperPrint jp
                    = net.sf.jasperreports.engine.JasperFillManager.fillReport(reportStream, parameters, DBConnection.getConnection());

            net.sf.jasperreports.view.JasperViewer.viewReport(jp, false);

        } catch (Exception e) {
            e.printStackTrace();
            JOptionPane.showMessageDialog(this, "Report error: " + e.getMessage(), "System Error", JOptionPane.ERROR_MESSAGE);
        }
    }//GEN-LAST:event_checkoutBtnActionPerformed

    private void removeitembtnActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_removeitembtnActionPerformed
        int selectedRow = cartTbl.getSelectedRow();

        if (selectedRow == -1) {
            JOptionPane.showMessageDialog(this, "Please select an item from the cart to remove.", "Selection Required", JOptionPane.WARNING_MESSAGE);
            return;
        }

        try {
            double lineTotal = Double.parseDouble(cartTbl.getValueAt(selectedRow, 4).toString());
            DefaultTableModel model = (DefaultTableModel) cartTbl.getModel();
            model.removeRow(selectedRow);
            grandTotal -= lineTotal;
            lblGrandTotal.setText("Rs. " + String.format("%.2f", grandTotal));

        } catch (Exception e) {
            JOptionPane.showMessageDialog(this, "Error removing item: " + e.getMessage(), "System Error", JOptionPane.ERROR_MESSAGE);
        }
    }//GEN-LAST:event_removeitembtnActionPerformed


